package project.study.study_project.report.domain;

/**
 * 제보 한 건의 처리 상태(V17).
 *
 * <p><b>세 값뿐인 이유.</b> "확인 중" 같은 중간 상태를 두지 않았다. 1인 서비스라 제보를 읽는
 * 사람과 고치는 사람이 같아서, 중간 상태는 누구에게도 정보를 주지 못하면서 제보함의 필터만
 * 하나 늘린다. 파생 가능하거나 아무도 안 보는 상태는 만들지 않는다는 이 저장소의 원칙과 같다
 * (스트릭을 저장하지 않고, "미복습"을 컬럼으로 두지 않은 것과 같은 판단).
 *
 * <p><b>인정과 기각을 가르는 기준</b>은 "제보가 맞았는가"이지 "고쳤는가"가 아니다.
 * 인정된 제보만 다음 생성 프롬프트로 되먹여지므로, 여기서 갈리는 것은 <b>모델에게 전할 사례인가</b>다.
 * 실제 수정은 문제 관리 화면에서 따로 한다 — 제보함이 문제를 고치는 화면까지 겸하면
 * "읽고 판단하는 일"과 "고치는 일"이 한 화면에 섞인다(관리 콘솔을 일의 단계로 가른 이유).
 */
public enum ReportStatus {

    /** 접수됨. 아직 사람이 안 봤다 — 제보함 배지가 세는 것이 이 상태다. */
    PENDING,

    /** 지적이 맞다고 판단. 이 건의 사유가 다음 생성 프롬프트에 되먹여진다. */
    ACCEPTED,

    /** 지적이 틀렸거나 문제가 아니라고 판단. 되먹임에 쓰이지 않는다. */
    DISMISSED
}
