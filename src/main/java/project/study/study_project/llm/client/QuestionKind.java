package project.study.study_project.llm.client;

/**
 * 문제가 <b>어떤 형태로</b> 묻는지 — 2026-08-25 신설.
 *
 * <p><b>왜 필요한가.</b> 중급이 오래 상황 적용형 하나로만 나왔다. 프롬프트의
 * {@code [난이도가 뜻하는 것]}이 중급을 "원리를 처음 보는 상황에 적용, 지문에 상황이 한 문단"으로
 * 못 박아 다른 형태가 나올 자리가 없었기 때문이다. 그런데 같은 프롬프트의
 * {@code [난이도를 스스로 확인하는 법]}에는 "초급인데 두 개념을 나란히 놓고 물었다면 중급이다"가
 * 있었다 — <b>비교형은 이미 중급으로 분류돼 있는데 정의에는 없는</b> 모순이었다.
 * 그 모순을 없애며 형태를 다섯으로 열었고, 열었으면 <b>재야 한다</b>.
 *
 * <p><b>왜 모델이 직접 선언하게 하는가.</b> 지문만 보고 형태를 기계가 알아내려면 자연어를
 * 분류해야 하는데, 그건 정확도가 낮고 규칙이 바뀔 때마다 분류기를 다시 손봐야 한다.
 * 이 저장소는 같은 문제를 이미 한 번 풀었다 — 근거 인용({@code sourceQuote})도
 * "문서에서 베꼈는지"를 추론하는 대신 <b>스키마 필드로 받아 기계가 대조</b>했다.
 * 여기서도 같은 처방을 쓴다: 모델이 적고, 검사는 그 선언과 실물의 <b>측정 가능한 부분</b>만 잰다.
 *
 * <p><b>알려진 한계.</b> 선언과 실물이 어긋날 수 있다 — 상황 지문을 써 놓고 {@link #COMPARISON}
 * 이라 우겨도 기계는 모른다. 그건 검수자 몫으로 남긴다. {@code sourceQuote}도 같은 한계를
 * 안고 쓰고 있고, 그래도 <b>아무것도 안 재는 것보다 낫다</b>는 것이 그때의 결론이었다.
 * 실제로 잡히는 것은 "상황형이라 선언했는데 지문이 80자"처럼 <b>선언 자체와 부딪히는</b> 경우다.
 *
 * <p><b>검사는 중급에만 적용한다.</b> 초급은 정의를 묻는 자리라 형태를 나눌 것이 없고
 * (상황이 붙으면 그건 중급이다), 고급은 정의상 언제나 {@link #SITUATION}이다
 * ("상황과 이미 시도한 것이 지문에 있다"). 나눠서 이득이 있는 곳은 중급뿐이다.
 */
public enum QuestionKind {

    /**
     * 상황 적용 — 실무 장면을 주고 원인이나 판단을 묻는다.
     *
     * <p>면접에서 가장 많이 나오는 형태라 <b>배치의 기본값</b>으로 지킨다
     * ({@code ProblemItemRule.SITUATION_MIN_PER_BATCH}). 다섯 형태를 다 열어 두면
     * 모델이 쓰기 쉬운 쪽으로 쏠릴 수 있는데, 쏠려서 곤란한 방향은 <b>상황형이 사라지는 쪽</b>이다.
     */
    SITUATION("상황 적용"),

    /**
     * 비교·선택 — 두 방식을 나란히 놓고 무엇이 가르는지 묻는다.
     *
     * <p><b>고급과 헷갈리는 자리다.</b> 고급도 "여러 대응 중 무엇을 고를지"를 묻는다.
     * 경계는 상황의 유무다 — 중급은 <b>원리 자체의 기준</b>("Write-Back이 유리한 조건은?"),
     * 고급은 <b>주어진 상황에서의 선택</b>(지문에 상황과 이미 시도한 것이 있다).
     */
    COMPARISON("비교·선택"),

    /** 인과·메커니즘 — "왜 그렇게 하는가"를 직접 묻는다. 문서의 {@code ### 왜 이렇게 설계됐는가}와 가장 가깝다. */
    CAUSE("인과·메커니즘"),

    /**
     * 진술 판정 — 진술 넷 중 옳거나 틀린 것을 고른다. 지문이 짧고 보기가 본문이 된다.
     *
     * <p><b>초급으로 새기 가장 쉬운 형태다.</b> 초급도 "정의 넷 중 옳은 것"으로 낼 수 있다.
     * 경계는 진술의 내용이다 — 초급은 <b>정의</b>, 중급은 <b>동작·판단</b>에 관한 진술이다.
     * 고급으로 새는 것도 막아야 한다: 넷이 전부 그럴듯하면 그건 고급이므로,
     * 판정형에도 "명백히 틀린 오답이 있어야 한다"는 중급 규칙이 그대로 적용된다.
     */
    JUDGMENT("진술 판정"),

    /**
     * 순서·절차 — 단계가 있는 동작의 순서를 묻는다.
     *
     * <p>재료가 있는 주제가 제한적이다(캐시 무효화·트랜잭션처럼 순서가 결과를 가르는 주제).
     * 그래서 <b>개수를 박지 않는다</b> — 억지로 만들라고 하면 순서가 중요하지 않은 주제에
     * 순서를 지어낸다. 기존 {@code [개수를 채우지 못할 때]} 규칙에 맡긴다.
     */
    SEQUENCE("순서·절차");

    private final String label;

    QuestionKind(String label) {
        this.label = label;
    }

    /** 검수 화면에 뿌릴 한글 이름 — docs/02의 "enum은 영문, 표기는 한글" 규칙. */
    public String getLabel() {
        return label;
    }
}
