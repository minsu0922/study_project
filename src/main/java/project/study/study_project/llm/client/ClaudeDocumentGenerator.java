    /**
     * 실제 API 호출 — 두 편이 <b>시스템 프롬프트와 user 메시지만</b> 다르다.
     *
     * <p>편마다 메서드를 통째로 복제하지 않은 이유: 모델·토큰 상한·사고 설정·예외 변환은
     * 편과 아무 상관이 없다. 복제하면 다음에 한쪽만 고쳐서 어긋난다 —
     * {@code ClaudeProblemGenerator}가 업로드 경로를 갈랐을 때 내린 것과 같은 판단이다
     * (양식에 묶인 곳만 가른다).
     */
    private GeneratedDocumentItem call(String systemPrompt, String userMessage, DocumentEdition edition) {
        StructuredMessageCreateParams<GeneratedDocumentItem> params = MessageCreateParams.builder()
                .model(model)
                .maxTokens(MAX_TOKENS)
                // 개념 문서 쓰기는 "무엇을 넣고 무엇을 뺄지"를 계속 저울질하는 작업이라 사고가 도움이 된다.
                // 문제 생성과 같은 판단(ClaudeProblemGenerator 주석)이므로 설정도 같게 둔다.
                .thinking(ThinkingConfigAdaptive.builder().build())
                .system(systemPrompt)
                .outputConfig(GeneratedDocumentItem.class)
                .addUserMessage(userMessage)
                .build();

        try {
            return AnthropicClientHolder.get().messages().create(params).content().stream()
                    .flatMap(block -> block.text().stream())
                    .findFirst()
                    .map(typed -> typed.text())
                    .orElseThrow(() -> new BusinessException(ErrorCode.LLM_003,
                            "모델 응답에 문서가 없습니다(%s).".formatted(edition.getDisplayName())));
        } catch (AnthropicServiceException e) {
            log.warn("Claude API 호출 실패(문서 생성 {}): status={}, message={}",
                    edition, e.statusCode(), e.getMessage());
            throw new BusinessException(ErrorCode.LLM_003, "Claude API 오류: " + e.getMessage());
        } catch (AnthropicIoException e) {
            log.warn("Claude API 네트워크 오류(문서 생성 {}): {}", edition, e.getMessage());
            throw new BusinessException(ErrorCode.LLM_003, "네트워크 오류로 문서 생성에 실패했습니다.");
        }
    }

