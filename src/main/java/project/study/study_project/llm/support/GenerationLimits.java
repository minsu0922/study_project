package project.study.study_project.llm.support;

/**
 * 한 번에 몇 문제까지 만들 수 있는가 — <b>요금이 걸린 숫자</b>라 한 곳에만 둔다.
 *
 * <h2>왜 상수로 뽑았나(2026-08-29)</h2>
 *
 * <p>상한 10이 {@code LlmGenerateRequest}와 {@code LlmDocumentGenerateRequest} 두 곳에
 * {@code @Max(10)}으로 복사돼 있었고, 배치 진입점({@code DraftGeneratorCli})에는
 * <b>아예 없었다</b>. 관리자 화면은 11을 거부하는데 워크플로 수동 입력은 500을 그대로
 * 받아 넘기는 상태였다 — 같은 기능의 두 입구가 다른 규칙을 갖고 있었고, 검증이 없는 쪽이
 * 하필 사람이 손으로 숫자를 적어 넣는 쪽이었다.
 *
 * <p>세 번째 사본을 만드는 대신 상수 하나로 모은다. 이 저장소가 여러 번 겪은 실패가
 * "같은 규칙이 두 곳에 생겨 언젠가 한쪽만 바뀌는 것"이었다.
 *
 * <h2>왜 하필 10인가</h2>
 *
 * <p>호출 한 번의 <b>요금과 응답 시간을 예측 가능하게</b> 묶는 값이다. 어댑티브 사고를 켜 둬서
 * 5문제에 수 분이 걸리는데, 개수를 키우면 러너 시간 상한(20분)에 먼저 걸린다. 검수 쪽 사정도
 * 있다 — 한 번에 쏟아지는 초안이 많을수록 사람이 대충 보게 된다.
 *
 * <p>범위를 벗어난 값은 <b>잘라 쓰지 않고 거부한다.</b> 50을 적었는데 조용히 10이 나오면
 * 사람은 50이 나온 줄 안다. 잘못 적었다는 사실 자체를 알려 주는 편이 낫고, 호출 전에 막으므로
 * 요금은 0이다.
 */
public final class GenerationLimits {

    /** 한 번에 만들 수 있는 최소 개수. 0이나 음수는 "만들지 않겠다"는 뜻이 아니라 오타다. */
    public static final int MIN_COUNT = 1;

    /** 한 번에 만들 수 있는 최대 개수(위 설명). */
    public static final int MAX_COUNT = 10;

    private GenerationLimits() {
    }
}
