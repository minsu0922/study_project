-- V13__problem_title.sql — 문제에 "목록에 뜰 이름"을 붙인다 (2026-08-21)
-- =====================================================================
-- 기준 문서: docs/18-problem-list-ui.md (문제 목록 화면 스펙 — 1단계 "데이터")
--
-- [왜 필요한가]
-- 문제 목록 화면은 한 행에 제목 한 줄(14px)을 보여 준다. 그런데 problem 테이블에는
-- 지문(question)밖에 없다. 지문의 앞부분을 잘라 쓰면 이렇게 나온다:
--   "주문 API에서 처리 건수를 세려고 서비스 클래스에 static 카운터를 두고 요청마다…"
-- 무엇을 묻는 문제인지 알 수 없다. 게다가 2026-08-18에 중급·고급 지문을
-- <실무 장면>으로 쓰게 바꾸면서(ClaudeProblemGenerator의 [상황 지문 쓰는 법])
-- 지문 첫 문장은 이제 <상황 서술>이지 주제가 아니다. 잘라 쓰기가 더 나빠졌다.
-- 목록에서 고를 수 있게 하려면 "이 문제가 무엇에 관한 것인가"를 따로 들고 있어야 한다.
--
-- [왜 NULL 허용인가]
-- 이 컬럼이 생기기 전에 만들어진 문제 33건에는 채워 넣을 값이 없다. NOT NULL로 만들려면
-- 여기서 UPDATE로 아무 값이나 넣어야 하는데(지문 앞부분 같은 것), 그러면 <가짜 제목이
-- 진짜 제목인 척> 들어앉아 나중에 백필해야 할 대상을 구분할 수 없게 된다.
-- NULL은 "아직 없다"를 정직하게 말한다 — 백필은 이 값이 NULL인 행만 고르면 된다.
--
-- [왜 120자인가]
-- 화면이 실제로 소화하는 길이는 훨씬 짧다(목록 한 줄, 대략 35자). 그 상한은
-- 프롬프트와 검증기가 잡는다(ProblemItemRule.TITLE_MAX) — 여기서 짧게 막으면
-- 한 글자 넘겼다고 <저장 자체가 실패>한다. 이 저장소의 규칙 그대로다:
-- 품질 기준은 경고로 알리고, DB 제약은 사고를 막는 선까지만 건다.
--
-- [인덱스를 만들지 않은 이유]
-- 목록 화면은 제목으로 검색하거나 정렬하지 않는다(정렬은 풀이 상태·도메인·난이도).
-- 제목은 <읽어서 보여 주는> 값이라 조회 조건에 오르지 않는다. 검색 기능이 생기면
-- 그때 FULLTEXT를 고민한다 — 접두 일치가 아니라 부분 일치가 필요할 것이므로
-- 지금 B-tree 인덱스를 걸어 두면 그때 쓰이지도 않는다.
-- =====================================================================

-- 정식 문제 — 승인 시 초안에서 그대로 옮겨 온다
ALTER TABLE problem
    ADD COLUMN title VARCHAR(120) NULL COMMENT '목록에 뜰 한 줄 제목(없으면 NULL — 화면이 지문으로 대체)' AFTER type;

-- 검수 대기 초안 — 검수자도 목록에서 제목으로 훑어야 한다
ALTER TABLE generated_problem_draft
    ADD COLUMN title VARCHAR(120) NULL COMMENT '목록에 뜰 한 줄 제목(없으면 NULL)' AFTER type;
