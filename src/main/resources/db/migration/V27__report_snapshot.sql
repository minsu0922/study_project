-- =====================================================================
-- V27__report_snapshot.sql — 신고가 들어온 순간의 내용을 신고에 남긴다
-- =====================================================================
-- 신고된 글을 글쓴이가 고치면 관리자는 신고함에서 고친 뒤의 내용만 봤다. 광고 글을 올렸다가
-- 신고되면 멀쩡한 글로 바꿔 빠져나갈 수 있었다. 수정을 막지는 않는다 — 멀쩡한 글도 신고 한 번에
-- 잠기게 된다(2026-10-05 사용자 결정). 대신 신고 당시의 내용을 신고 행에 베껴 둔다.
--
-- 모든 수정을 쌓는 이력 표를 두지 않는 이유: 관리자가 판정에 쓰는 것은 "신고된 그 내용" 하나다.
-- =====================================================================

ALTER TABLE comment_report
    -- 글 신고일 때만 채운다. 댓글에는 제목이 없다.
    ADD COLUMN snapshot_title VARCHAR(100)  NULL,
    -- NULL 허용: 이 칸이 생기기 전의 신고에는 남겨 둔 것이 없다. 그때는 지금 내용을 보여 준다.
    ADD COLUMN snapshot_body  VARCHAR(5000) NULL;
