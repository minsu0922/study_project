-- 처리 기록(V35)은 불린 주소로 대상을 알려 주는데, 등록은 주소에 번호가 없다
-- (POST /api/admin/problems). 그래서 "문제 등록" 줄만 무엇을 만들었는지 알 수 없었다.
--
-- 주소 칸(path)에 번호를 덧붙이지 않고 칸을 따로 둔다. path는 "실제로 불린 주소"라는
-- 뜻을 지켜야 수정·삭제 줄과 같은 눈으로 읽힌다.
-- =====================================================================

ALTER TABLE admin_audit_log
    ADD COLUMN created_id BIGINT NULL AFTER path;
