-- V41__draft_code_kind.sql — 코드 문제 초안에 유형과 예상 출력을 남긴다
-- =====================================================================
-- 코드와 언어 칸은 V39가 만들었다. 여기서는 검수자가 보는 두 가지를 더한다.
--   code_kind       — 다섯 유형 중 무엇인가(실행 결과, 빈칸 코드, 오류 지점, 컴파일 여부, 한 줄 고치기)
--   expected_output — 배치가 실제로 돌려 확인한 출력. 검수자가 정답 보기와 눈으로 한 번 더 견준다
--
-- 정식 문제(problem)에는 두지 않는다. 사용자 화면은 코드가 있으면 "코드 문제"로만 표시하고,
-- 예상 출력은 정답을 그대로 드러내는 값이라 내려보낼 일이 없다.
-- =====================================================================

ALTER TABLE generated_problem_draft
    ADD COLUMN code_kind VARCHAR(15) NULL AFTER code_language,
    ADD COLUMN expected_output TEXT NULL AFTER code_kind;
