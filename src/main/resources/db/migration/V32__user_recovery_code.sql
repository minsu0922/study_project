-- =====================================================================
-- V32__user_recovery_code.sql — 비밀번호를 잊었을 때 쓰는 복구 코드
-- =====================================================================
-- 이 서비스는 메일을 보내지 않아(V12) 재설정 메일을 보낼 곳이 없고,
-- 그래서 비밀번호를 잊으면 계정과 학습 기록을 되찾을 방법이 없었다.
--
-- 메일 대신 가입 때 한 번 보여 주는 복구 코드를 쓴다. 메일 서버와 발송 비용이 들지 않고,
-- "이메일을 받지 않는다"는 기존 결정도 그대로 둔다.
--
-- 비밀번호와 같은 값(이것만 알면 계정을 가져간다)이라 해시만 저장한다.
-- NULL은 이 컬럼보다 먼저 가입해 아직 발급받지 않은 계정이다.
-- =====================================================================

ALTER TABLE user
    ADD COLUMN recovery_code_hash VARCHAR(255) NULL AFTER password_hash;
