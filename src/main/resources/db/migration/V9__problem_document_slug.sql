-- =====================================================================
-- V9__problem_document_slug.sql — 문제 ↔ 개념 문서 느슨한 연결 (2단계)
-- =====================================================================
-- 기준 문서: docs/15-llm-concept-documents.md
--
-- 문제가 "어느 개념 문서를 근거로 만들어졌는지"를 기록한다. 4일 주기로
-- 1일차에 문서를 쓰고 2·3·4일차에 그 문서로 초급/중급/고급 문제를 만드는데,
-- 그 연결을 남겨야 학습자가 문제에서 막혔을 때 돌아가 읽을 곳이 생긴다.
--
-- [왜 FK가 아니라 slug 문자열인가]
-- 1. 문서보다 문제가 먼저 들어올 수 있다. 문제 초안은 흡수되자마자 이 값을 갖는데,
--    근거가 된 문서는 아직 검수 대기라 document 테이블에 없을 수 있다.
--    FK를 걸면 이 순간 INSERT가 통째로 실패한다 — 순서를 강제할 방법이 없는 구조다.
-- 2. 문서를 지웠다고 문제까지 지워지거나(CASCADE) 문서 삭제가 막히면(RESTRICT) 곤란하다.
--    문제는 문서 없이도 그 자체로 완결된 콘텐츠다.
-- 3. 연결이 끊어져도(오타·slug 변경) 손해가 "링크가 안 뜬다"뿐이다. 이 정도 손해에
--    무결성 제약의 경직성을 사는 것은 비싸다. 화면은 slug로 조회해 없으면 링크를 숨긴다.
--
-- [인덱스를 만들지 않은 이유]
-- 조회 방향이 "문제 → 문서"뿐이고, 그건 문제 행에 이미 들어 있는 값을 읽는 것이라
-- 인덱스가 필요 없다. 반대 방향("이 문서로 만든 문제 목록")은 아직 화면이 없다 —
-- 3단계에서 필요해지면 그때 추가한다(쓰지 않는 인덱스는 INSERT를 느리게 할 뿐이다).
-- =====================================================================

-- 정식 문제 — 승인 시 초안에서 그대로 옮겨 온다
ALTER TABLE problem
    ADD COLUMN document_slug VARCHAR(150) NULL COMMENT '근거 개념 문서의 slug(FK 아님, 없으면 NULL)';

-- 검수 대기 초안 — 흡수 시점에 생성 파일의 값을 그대로 기록한다
ALTER TABLE generated_problem_draft
    ADD COLUMN document_slug VARCHAR(150) NULL COMMENT '근거 개념 문서의 slug(FK 아님, 없으면 NULL)';
