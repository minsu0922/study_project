-- =====================================================================
-- V16__choice_match_text.sql — 짝짓기의 오른쪽 열을 보기 행에 붙인다 (2026-08-31)
-- =====================================================================
-- 기준: docs/01-data-model.md(타입별 answer 규약), ProblemType.MATCHING
--
-- [왜 필요한가]
-- 짝짓기 문제는 왼쪽(용어) 4개와 오른쪽(설명) 4개를 연결하게 한다. 지금 choice 테이블은
-- 한 행에 <보기 하나>만 담을 수 있어서 이 형태를 표현할 자리가 없었다.
--
-- [왜 "한 행 = 한 쌍"인가 — 버린 대안 둘]
-- ① 오른쪽 항목도 각각 choice 행으로 넣고(seq 1..4 = 왼쪽, 11..14 = 오른쪽) 짝은
--    problem.answer에 "1-13|2-11|…"로 적는 안. 컬럼을 안 늘려도 되지만 왼쪽/오른쪽 구분이
--    <seq 번호대의 관례>에 얹힌다. 그 관례를 모르는 코드가 하나만 생겨도 오른쪽 항목이
--    보기로 새어 나온다. 게다가 짝이 문자열 안에 있어 SQL로는 "4쌍이 다 있는가"를 못 본다.
-- ② 쌍 목록을 problem에 JSON 한 칸으로 넣는 안. ①과 같은 약점(조회·검증 불가)에
--    JSON 파싱이 더해진다.
-- 한 행이 한 쌍이면 짝이 <데이터 자리>에 있다. 왼쪽은 text, 오른쪽은 match_text이고,
-- "쌍이 몇 개인가"는 행을 세면 된다. 이 저장소가 오답 설명을 해설에서 파싱하는 대신
-- 보기 행에 붙인 것과 같은 판단이다(V15 주석 참고).
--
-- [짝짓기의 answer는 NULL이다]
-- 정답이 행 자체에 있으므로 채점 기준값을 따로 둘 이유가 없다 — 객관식이 정답을
-- is_correct에 두고 answer를 비우는 것과 같은 규약이다(docs/01).
-- 반대로 순서 배열(ORDERING)은 항목만 행으로 두고 <정답 순서>를 answer에 "3|2|1|4"로 적는다.
-- 순서는 행 사이의 관계라 어느 한 행에도 담기지 않기 때문이다.
--
-- [왜 NULL 허용인가]
-- 이 컬럼은 짝짓기 문제의 보기에만 값이 있다. 객관식·순서 배열의 보기 행에는 채워 넣을
-- 값이 없고, NOT NULL로 만들면 그 자리에 빈 문자열 같은 가짜 값을 넣어야 한다.
-- V13(problem.title)·V15(choice.rationale)와 같은 판단이다.
--
-- [왜 500자인가]
-- 왼쪽 열(text)과 같은 폭으로 맞췄다. 짝짓기의 오른쪽은 개념 하나를 가르는 한 문장이라
-- 실제로는 40~80자에 들어오지만, 폭을 다르게 잡으면 "왼쪽에 긴 문장, 오른쪽에 용어"로
-- 뒤집어 출제했을 때만 저장이 실패한다 — 방향에 따라 되고 안 되는 제약은 나중에
-- 원인을 찾기 어렵다. 품질 기준(오른쪽이 너무 길다 등)은 ProblemItemRule이 경고로 알린다.
-- =====================================================================

ALTER TABLE choice
    ADD COLUMN match_text VARCHAR(500) NULL
        COMMENT '짝짓기의 오른쪽 항목(이 행의 text와 짝. 짝짓기가 아닌 보기는 NULL)' AFTER `text`;
