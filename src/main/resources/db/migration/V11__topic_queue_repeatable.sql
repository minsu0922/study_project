-- [무엇이 바뀌었나 — 사용자 결정]
-- V10의 대기열은 <티켓>이었다. 한 줄 = 문서 한 편이고, 쓰면 사라진다.
-- 그런데 사용자가 원한 것은 "java, spring 같은 세분화 주제를 던져 주는 것"이었다 —
-- 그건 한 편짜리 주제가 아니라 <범위>다. 범위는 한 번 쓰고 버리는 것이 아니라
-- 우물처럼 계속 퍼 올린다: Spring 범위에서 오늘은 트랜잭션 전파, 다음엔 Bean 생명주기.
--
-- [왜 컬럼 이름을 바꾸나]
-- used_at은 "이걸 썼다(그래서 끝났다)"는 뜻이었다. 이제는 "마지막으로 쓴 날"이고,
-- 그 값은 <다음 차례를 정하는 근거>로 쓰인다(가장 오래 안 쓴 범위부터).
-- 뜻이 바뀐 컬럼에 옛 이름을 두면, 코드를 읽는 사람이 계속 "쓰면 끝나는 것"으로 읽는다.
-- 데이터는 그대로 옮겨진다(CHANGE COLUMN은 값을 보존한다).
--
-- [used_count를 왜 두나]
-- 범위는 마르는 순간이 온다 — Spring으로 스무 편을 쓰면 남은 주제가 억지스러워진다.
-- 실패가 조용한 종류라(문서는 계속 나온다) 사람이 알아채려면 숫자가 보여야 한다.
-- 화면에서 "이 범위로 몇 편 썼는지"를 보고 범위를 갈아 끼우는 판단을 한다.
-- =====================================================================

ALTER TABLE topic_queue
    -- NULL이면 아직 한 번도 안 쓴 범위. 정렬에서 NULL이 먼저 오므로(MySQL ASC)
    -- "새로 넣은 범위가 다음 차례"가 규칙을 따로 적지 않아도 성립한다.
    CHANGE COLUMN used_at last_used_at DATE NULL,

    -- 이 범위로 만든 문서 편수. 배치가 파일에 적어 보내면 앱이 기동할 때 받아 온다.
    -- DEFAULT 0은 기존 행을 위한 것이다(V10 시절 행에는 이 값이 없다).
    ADD COLUMN used_count INT NOT NULL DEFAULT 0;
