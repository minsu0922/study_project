-- [왜 필요한가 — 번호로 가리킬 수 없다는 제약에서 출발했다]
-- 사용자가 다듬은 해설은 오답을 "②번", "③번"처럼 번호로 지목한다. 읽기 좋은 형태지만
-- 지금 구조에서는 쓸 수 없다. 보기는 요청마다 다시 섞어서 내보내기 때문이다
-- (QuizChoiceItem.shuffledFrom). 섞는 이유는 위치 편향이다 — 승인된 17문제의 정답 위치가
-- 1번 6개·2번 6개·3번 5개·4번 0개였고(균등하면 확률 0.8%), 이 편향은 프롬프트로 안 고쳐진다.
-- 그래서 ProblemItemRule은 번호로 가리킨 해설을 <저장 단계에서 통째로 버린다>.
--
-- 번호를 쓰려면 섞기를 버려야 하고, 섞기를 버리면 4번을 찍지 않는 요령이 생긴다.
-- 학습 도구에서는 그쪽 손해가 더 크다. 그래서 셋째 길을 택했다:
-- <오답 설명을 보기 행에 붙이고, 화면이 섞인 순서대로 번호를 다시 매긴다.>
-- 채점이 이미 보기 id로 이뤄지므로(Choice.id) 순서가 바뀌어도 짝은 안 어긋난다.
--
-- [왜 problem.explanation을 쪼개지 않고 컬럼을 새로 만드나]
-- explanation은 통짜 문자열이라 "어느 오답에 대한 설명인지"가 글 안에만 있다. 그것을
-- 파싱해 보기와 짝지으려면 큰따옴표 인용을 다시 세야 하는데, 그건 지금 ProblemItemRule이
-- <대리 지표>로만 쓰는 방식이다(정확하지 않다는 것을 알고 쓰는 중). 데이터가 있어야 할
-- 자리에 두면 셀 필요가 없다 — 보기 하나에 설명 하나가 열로 붙는다.
--
-- [왜 NULL 허용인가]
-- V13(problem.title)과 같은 판단이다. 이 컬럼이 생기기 전에 승인된 문제들은 오답 설명이
-- 통짜 해설 안에 녹아 있어 채워 넣을 값이 없다. NOT NULL로 만들면 여기서 가짜 값을 넣어야
-- 하고, 그러면 백필 대상을 구분할 수 없게 된다. 화면은 rationale이 하나도 없는 문제를
-- <옛 형식>으로 알아보고 통짜 해설을 그대로 그린다 — 두 형식이 공존한다.
--
-- [왜 정답 보기는 비워 두나]
-- 정답의 근거는 problem.explanation이 통째로 맡는다("정답인 이유"). 정답 보기에도 한 줄을
-- 요구하면 같은 말이 두 곳에 생기고, 언젠가 한쪽만 고쳐진다. 이 저장소가 승인 경로를
-- AdminProblemService.create 하나로 묶어 둔 것과 같은 판단이다(단일 경로 원칙).
-- 그래서 이 컬럼은 <오답 보기에만> 값이 있다.
--
-- [왜 1000자인가]
-- 실측 기준이다. 사용자가 다듬은 예시의 오답 한 줄이 50~90자였고, 근거를 한 문장 더 붙이면
-- 200자대가 된다. 1000자는 그 네 배가 넘어 사고를 막는 선으로만 작동한다.
-- 품질 기준(너무 짧다/길다)은 ProblemItemRule이 경고로 알린다 — DB 제약으로 막으면
-- 한 글자 넘겼다고 저장 자체가 실패한다. V13 주석과 같은 규칙이다.
-- =====================================================================

-- 정식 문제의 보기 — 승인 시 초안에서 그대로 옮겨 온다
ALTER TABLE choice
    ADD COLUMN rationale VARCHAR(1000) NULL
        COMMENT '이 오답이 왜 틀렸는지 한 줄(정답 보기는 NULL — 근거는 problem.explanation)' AFTER is_correct;

-- 검수 대기 초안은 보기를 JSON 문자열(generated_problem_draft.choices_json)로 들고 있어
-- 컬럼을 더할 곳이 없다. 그쪽은 스키마 변경 없이 필드 하나가 늘 뿐이다 — 초안의 보기를
-- JSON으로 둔 결정이 여기서 값을 한다(GeneratedProblemDraft 주석 참고).
