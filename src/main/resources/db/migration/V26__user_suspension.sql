-- =====================================================================
-- 관리자가 글을 가릴 수는 있어도 같은 사람이 계속 올리는 것은 막을 수 없었다.
-- 정지는 쓰기(글·댓글·신고)만 막는다. 학습과 읽기는 그대로다(2026-10-05 사용자 결정).
--
-- 지금 상태만 둔다. 이력 표를 따로 두지 않는 이유: 아직 이력을 읽는 화면이 없다.
-- 필요해지면 그때 표를 만들고, 그전까지는 서버 로그에 남는다.
-- =====================================================================

ALTER TABLE `user`
    -- 이 시각까지 정지다. NULL이거나 지난 시각이면 정지가 아니다 — 기간이 끝나면 아무도 풀지 않아도 풀린다.
    -- 무기한은 9999-12-31로 적는다(User.INDEFINITE). 칸을 하나 더 두면 "둘 중 어느 쪽이 맞나"가 생긴다.
    ADD COLUMN suspended_until  DATETIME(6)  NULL,
    -- 정지된 사람에게 그대로 보여 주는 말이다.
    ADD COLUMN suspended_reason VARCHAR(200) NULL;
