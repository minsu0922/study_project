-- =====================================================================
-- 문제 초안에 "묻는 형태"를 기록한다 — 2026-08-25
--
-- [왜 필요한가]
-- 중급이 오랫동안 상황 적용형 하나로만 나왔다. 프롬프트의 [난이도가 뜻하는 것]이
-- 중급을 "지문에 상황이 한 문단"으로 못 박아 다른 형태가 나올 자리가 없었기 때문이다.
-- 같은 날 형태를 다섯으로 열면서(QuestionKind) 검사도 함께 붙였는데, 검사가
-- <조회 시점에> 돌려면 초안 행이 자기 형태를 알고 있어야 한다.
--
-- [왜 조회 시점에 검사하나 — 저장해 두지 않고]
-- 문서 초안이 이미 그렇게 한다(LlmDocumentService.toResponse). 검사 결과를 저장하면
-- 규칙을 고쳐도 이미 대기 중인 초안은 옛 판정을 달고 있다. 규칙을 고치는 일이
-- 이 파이프라인에서는 자주 있는 일이라, "지금 규칙으로 다시 본다"가 맞다.
-- 그래서 저장하는 것은 <판정>이 아니라 판정에 필요한 <입력>이다.
--
-- [NULL을 허용하는 이유]
-- 이 컬럼이 생기기 전에 만들어진 초안이 이미 있다(2026-08-25 기준 58건).
-- NOT NULL로 두면 마이그레이션이 기본값을 지어내야 하는데, 그 기본값은 거짓이다 —
-- 그 초안들이 실제로 무슨 형태였는지는 아무도 모른다. 검사 쪽은 NULL을
-- "선언 안 함"으로 보고 조용히 넘어간다. 옛 초안이 갑자기 경고를 달고 나오면
-- 검수자가 경고를 안 보게 되는데, 그것이 이 저장소가 이미 겪은 실패 방식이다.
--
-- [problem 테이블에는 넣지 않는다]
-- document_slug(V9)는 학습자 화면의 링크에 쓰이므로 정식 문제까지 따라갔다.
-- 이 값은 <출제 품질을 재는 데만> 쓰이고 학습자에게 보일 일이 없다. 승인된 뒤에는
-- 다시 잴 일도 없다 — 검수를 통과했다는 것이 이미 판정이다.
-- 쓰지 않을 컬럼을 미리 만들어 두면 "이건 왜 늘 NULL이지"가 남는다.
--
-- [길이 15인 이유]
-- 가장 긴 상수가 COMPARISON(10자)이다. Difficulty(15)·ProblemType(20)과 같은 방식으로
-- 여유를 조금 얹는다. enum 이름을 문자열로 넣는 것은 이 저장소의 규칙이다
-- (@Enumerated(EnumType.STRING)) — ORDINAL은 상수 순서를 바꾸는 순간 과거 데이터가
-- 통째로 다른 뜻이 된다.
-- =====================================================================

ALTER TABLE generated_problem_draft
    ADD COLUMN question_kind VARCHAR(15) NULL
        COMMENT '묻는 형태(SITUATION/COMPARISON/CAUSE/JUDGMENT/SEQUENCE). 도입 전 초안은 NULL';
